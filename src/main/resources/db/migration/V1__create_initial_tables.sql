
-- V1__create_initial_tables.sql

-- 1. Customers
CREATE TABLE customers (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(100) NOT NULL,
                           mobile_number VARCHAR(20) NOT NULL,
                           location VARCHAR(150),
                           reminder_consent BOOLEAN NOT NULL DEFAULT FALSE,
                           created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_customers_mobile_number
    ON customers(mobile_number);


-- 2. Vehicles
CREATE TABLE vehicles (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          customer_id BIGINT NOT NULL
                              REFERENCES customers(id),
                          vehicle_number VARCHAR(20) NOT NULL UNIQUE,
                          vehicle_type VARCHAR(30) NOT NULL DEFAULT 'BIKE',
                          vehicle_brand VARCHAR(80),
                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_vehicles_customer_id
    ON vehicles(customer_id);


-- 3. Oil brand master
CREATE TABLE oil_brands (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            brand_name VARCHAR(100) NOT NULL UNIQUE,
                            default_price NUMERIC(10, 2) NOT NULL
                                CHECK (default_price >= 0),
                            active BOOLEAN NOT NULL DEFAULT TRUE,
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 4. Oil service history
CREATE TABLE oil_services (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              vehicle_id BIGINT NOT NULL
                                  REFERENCES vehicles(id),
                              oil_brand_id BIGINT NOT NULL
                                  REFERENCES oil_brands(id),
                              service_date DATE NOT NULL,
                              oil_price NUMERIC(10, 2) NOT NULL
                                  CHECK (oil_price >= 0),
                              next_due_date DATE NOT NULL,
                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_oil_services_due_date
    ON oil_services(next_due_date);

CREATE INDEX idx_oil_services_vehicle_id
    ON oil_services(vehicle_id);