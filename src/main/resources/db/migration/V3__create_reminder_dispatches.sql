
CREATE TABLE reminder_dispatches (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                     service_record_id BIGINT NOT NULL UNIQUE
                                         REFERENCES service_records(id),

                                     status VARCHAR(20) NOT NULL,
                                     message TEXT NOT NULL,

                                     processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                     created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT chk_reminder_dispatch_status
                                         CHECK (status IN ('SIMULATED', 'SENT', 'FAILED'))
);

CREATE INDEX idx_reminder_dispatch_status
    ON reminder_dispatches(status);