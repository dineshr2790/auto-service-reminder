CREATE TABLE service_records (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 vehicle_id BIGINT NOT NULL
                                     REFERENCES vehicles(id),

                                 service_date DATE NOT NULL,

                                 oil_brand VARCHAR(80) NOT NULL,

                                 odometer_km INTEGER,

                                 amount_paid NUMERIC(10, 2),

                                 next_reminder_date DATE NOT NULL,

                                 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT chk_service_records_odometer
                                     CHECK (odometer_km IS NULL OR odometer_km >= 0),

                                 CONSTRAINT chk_service_records_amount
                                     CHECK (amount_paid IS NULL OR amount_paid >= 0)
);

CREATE INDEX idx_service_records_vehicle_date
    ON service_records (vehicle_id, service_date DESC);

CREATE INDEX idx_service_records_reminder_date
    ON service_records (next_reminder_date);